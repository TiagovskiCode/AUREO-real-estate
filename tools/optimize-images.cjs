/* Generates responsive WebP versions of every photo in images and a manifest
   (js/images.js) that the site uses to build srcset attributes.
   Run from the project root:  node tools/optimize-images.cjs */
const fs = require('fs')
const path = require('path')
const sharp = require('sharp')

const SRC = path.join(__dirname, '..', 'images')
const OUT = path.join(SRC, 'opt')
const WIDTHS = [640, 1200, 1920]

;(async () => {
  fs.mkdirSync(OUT, { recursive: true })
  const manifest = {}
  for (const file of fs.readdirSync(SRC).filter((f) => /\.jpe?g$/i.test(f))) {
    const name = file.replace(/\.jpe?g$/i, '')
    const meta = await sharp(path.join(SRC, file)).metadata()
    // Never upscale: keep the widths below the original, then the largest size we serve (original or 1920).
    const top = Math.min(meta.width, WIDTHS[WIDTHS.length - 1])
    const widths = WIDTHS.filter((w) => w < top)
    widths.push(top)
    manifest[name] = []
    for (const w of widths) {
      await sharp(path.join(SRC, file)).resize({ width: w }).webp({ quality: 74 }).toFile(path.join(OUT, `${name}-${w}.webp`))
      manifest[name].push(w)
    }
  }
  const js = '/* Generated by tools/optimize-images.cjs — available WebP widths per photo. */\nwindow.AUREO_IMAGES = ' + JSON.stringify(manifest, null, 2) + '\n'
  fs.writeFileSync(path.join(__dirname, '..', 'js', 'images.js'), js)
  console.log(manifest)
})()
